/**
 * お客さん向け「こんなお店は要注意」リスト。
 *
 * チェック項目（checks.ts）が「できているか」を店側の視点で並べたものなのに対し、
 * こちらは裏返して、お客さんが店に入ってから帰るまでに気づけるサインだけを集める。
 *
 * 載せる基準はひとつだけ：
 *   **お客さんが自分の目で見て分かること。**
 * 届出・名簿・お金の流れ・資本関係のように、外から見えないものは入れない。
 * 「他のお客さんの年齢」「照度が10ルクスあるか」のように、見ても判断がつかない
 * ものも入れない。見えないものを並べると、お客さんは判断できないまま不安だけ
 * 持ち帰ることになる。
 *
 * why は「なぜ問題か」を1文で。basis は checks.ts と同じ根拠に揃える。
 * step はそのサインを詳しく説明しているステップ。
 */
export type Sign = {
  id: string;
  /** 来店の流れのどこで気づくか */
  when: string;
  /** 気づけるサイン。「〜がない」「〜がある」で書く */
  sign: string;
  /** なぜ問題なのか */
  why: string;
  /** 根拠の条文・資料 */
  basis: string;
  /** 詳しく書いてあるステップ */
  step: string;
  /**
   * 見かけたらアウトが確定するわけではないが、強いサインになるもの。
   * 条文上まっすぐ説明できるものだけ true にする。
   */
  strong?: boolean;
};

