export const SIGN_COUNT = SIGNS.length;

/** 来店の流れの順に、サインをまとめる */
export function signsByWhen() {
  const out: { when: string; items: Sign[] }[] = [];
  for (const s of SIGNS) {
    const last = out[out.length - 1];
    if (last && last.when === s.when) last.items.push(s);
    else out.push({ when: s.when, items: [s] });
  }
  return out;
}
