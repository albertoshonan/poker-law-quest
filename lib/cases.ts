/**
 * 「これってOK？NG？」ケース集。
 *
 * 現場でよく出る場面を扱う。ただしこのアプリの原則はここでも同じで、
 * **言い切るのは、法令・警察ラベルで裏付けのあるものだけ**にする。
 *
 * そのため各ケースを「言えること」と「言えないこと」に分けて書く。
 * 5件のうち3件は、公開一次資料では結論が出ない。出ないことを隠して
 * それらしい答えを書くほうが、ケース集としてよほど危ない。
 *
 * verdict:
 *   "ng"    … 条文からまっすぐ説明できる。言い切ってよい
 *   "scope" … 条文の射程について言えることがある。ただし実態判断が残る
 *   "gray"  … 公開一次資料では結論が出ない。所轄への確認を勧める
 */
export type Verdict = "ng" | "scope" | "gray";

